export function createInitialGangBoard(randomize = true): Record<number, GangMemberSlot> {
  const board: Record<number, GangMemberSlot> = {};
  for (let num = 2; num <= 12; num++) {
    const pool = GANG_MEMBER_POOLS[num];
    const pick = randomize
      ? pool[Math.floor(Math.random() * pool.length)]
      : pool[0];

    board[num] = {
      number: num,
      title: pick.title,
      role: pick.role,
      avatar: pick.avatar,
      quote: pick.quote,
      baseSymbols: [...pick.baseSymbols],
      upgrades: [],
      assignedNecklace: null,
    };
  }
  return board;
}

